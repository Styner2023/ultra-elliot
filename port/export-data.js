eval(src + probe);

const E = globalThis.__export;
E.buildMap();

const grid = E.grid();
const roomGrid = E.roomGrid();

/* the map as text: '#' wall, '.' open. One string per row. */
const collision = grid.map((row) => row.map((c) => (c ? "#" : ".")).join(""));

/* room ownership per cell, 0 = solid. Base-36 keeps it one char per cell. */
const ownership = roomGrid.map((row, y) =>
  row.map((r, x) => (grid[y][x] ? "0" : r.toString(36))).join("")
);

let open = 0;
for (const row of grid) for (const c of row) if (!c) open++;

