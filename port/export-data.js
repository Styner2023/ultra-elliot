/*
 * Ultra Elliot - portable data export
 *
 * Runs the real game.js headlessly and dumps every piece of engine-agnostic
 * game data to JSON. No canvas, no DOM, no rendering: just the world, the
 * entities and the tuning numbers a native port needs.
 *
 * Regenerate after changing game.js:
 *     node port/export-data.js
 *
 * Nothing here is Nintendo-specific. It is equally useful for Unity, a C++
 * engine, Godot, or a rewrite of the browser version.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

/* ---- minimal stubs so game.js can be evaluated outside a browser ---- */

